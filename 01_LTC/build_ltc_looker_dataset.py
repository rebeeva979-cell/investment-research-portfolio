def validate(rows: list[dict]) -> dict:
    dates = [row["date"] for row in rows]
    duplicates = len(dates) - len(set(dates))
    gaps = []
    for previous, current in zip(dates, dates[1:]):
        delta = (current - previous).days
        if delta != 1:
            gaps.append({"previous": previous, "current": current, "missing_days": delta - 1})

    ohlc_violations = []
    missing_values = 0
    for row in rows:
        open_, high, low, close = (row[field] for field in PRICE_FIELDS)
        if not (high >= max(open_, close) and low <= min(open_, close) and low > 0):
            ohlc_violations.append(row["date"])
        if any(row[field] is None for field in PRICE_FIELDS) or row["volume"] is None:
            missing_values += 1

    return {
        "observations": len(rows),
        "start": dates[0],
        "end": dates[-1],
        "duplicates": duplicates,
        "gaps": gaps,
        "ohlc_violations": ohlc_violations,
        "missing_values": missing_values,
    }


