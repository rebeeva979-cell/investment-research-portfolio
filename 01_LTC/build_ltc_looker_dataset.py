def pct(numerator: float | None, denominator: float | None) -> float | None:
    if numerator is None or denominator in (None, 0):
        return None
    return (numerator / denominator - 1.0) * 100.0


def calendar_return(index: dict[dt.date, float], current_date: dt.date, days: int) -> float | None:
    """Return over an exact calendar interval; no interpolation across gaps."""
    target = current_date - dt.timedelta(days=days)
    if target not in index:
        return None
    return pct(index[current_date], index[target])


def trailing_mean(values: list[float], window: int) -> float | None:
    if len(values) < window:
        return None
    return sum(values[-window:]) / window


def annualized_volatility(returns: list[float | None], window: int = 30) -> float | None:
    clean = [value for value in returns[-window:] if value is not None]
    if len(clean) < window or len(clean) < 2:
        return None
    # return_*_pct is stored in percentage points (e.g. 4.2 means 4.2%).
    # Keep the result in percentage points as well. Do not multiply by 100 twice.
    return statistics.stdev(clean) * math.sqrt(365)


def rolling_risk_metrics(returns: list[float | None], window: int = 30) -> dict[str, float | None]:
    """Historical tail and risk-adjusted metrics in percentage-point returns.

    VaR uses the empirical nearest-rank lower tail. Sharpe and Sortino use
    zero minimum acceptable return and 365 crypto periods per year.
    """
    clean = [value for value in returns[-window:] if value is not None]
    blank = {
        "var_95_30d_pct": None,
        "var_99_30d_pct": None,
        "downside_deviation_30d_annualized_pct": None,
        "sharpe_30d": None,
        "sortino_30d": None,
    }
    if len(clean) < window or len(clean) < 2:
        return blank
    ordered = sorted(clean)

    def empirical_var(confidence: float) -> float:
        rank = max(1, math.ceil((1.0 - confidence) * len(ordered)))
        return ordered[rank - 1]

    daily_downside = math.sqrt(sum(min(value, 0.0) ** 2 for value in clean) / len(clean))
    daily_vol = statistics.stdev(clean)
    mean_return = statistics.mean(clean)
    blank.update(
        {
            "var_95_30d_pct": empirical_var(0.95),
            "var_99_30d_pct": empirical_var(0.99),
            "downside_deviation_30d_annualized_pct": daily_downside * math.sqrt(365),
            "sharpe_30d": mean_return / daily_vol * math.sqrt(365) if daily_vol else None,
            "sortino_30d": mean_return / daily_downside * math.sqrt(365) if daily_downside else None,
        }
    )
    return blank


def ratio(value: float | None) -> float | None:
    """Convert percentage points to a fraction for Looker Studio percent fields."""
    return value / 100.0 if value is not None else None


def halving_context(current_date: dt.date) -> tuple[int, int | None, int | None]:
    epoch = 0
    for item in HALVINGS:
        if current_date >= item["date"]:
            epoch = item["epoch"]
    known = [item for item in HALVINGS if not item["estimated"]]
    past = [item for item in known if current_date >= item["date"]]
    future = [item for item in HALVINGS if current_date < item["date"]]
    days_since = (current_date - past[-1]["date"]).days if past else None
    days_to_next = (future[0]["date"] - current_date).days if future else None
    return epoch, days_since, days_to_next


def enrich(rows: list[dict], onchain_rows: list[dict] | None = None) -> list[dict]:
    close_index = {row["date"]: row["price_close_usd"] for row in rows}
    closes = [row["price_close_usd"] for row in rows]
    volumes = [row["volume"] for row in rows]
    daily_returns = [row["return_1d_pct"] for row in rows]
    onchain_by_date = {row["date"]: row for row in (onchain_rows or []) if row.get("date")}

    first_close_by_year: dict[int, float] = {}
    for row in rows:
        first_close_by_year.setdefault(row["date"].year, row["price_close_usd"])

    high_water_mark = -math.inf
    high_water_date: dt.date | None = None
    enriched: list[dict] = []

    for position, row in enumerate(rows):
        current_date = row["date"]
        close = row["price_close_usd"]

        if close > high_water_mark:
            high_water_mark = close
            high_water_date = current_date

        ma_7 = trailing_mean(closes[: position + 1], 7)
        ma_30 = trailing_mean(closes[: position + 1], 30)
        ma_90 = trailing_mean(closes[: position + 1], 90)
        ma_200 = trailing_mean(closes[: position + 1], 200)
        volume_ma_30 = trailing_mean(volumes[: position + 1], 30)
        rolling_risk = rolling_risk_metrics(daily_returns[: position + 1])

        epoch, days_since_halving, days_to_next_halving = halving_context(current_date)
        previous_date = rows[position - 1]["date"] if position else None

        record = {
                "date": current_date,
                "asset": ASSET,
                "price_open_usd": row["price_open_usd"],
                "price_high_usd": row["price_high_usd"],
                "price_low_usd": row["price_low_usd"],
                "price_close_usd": close,
                "volume": row["volume"],
                "return_1d_pct": row["return_1d_pct"],
                "return_7d_pct": calendar_return(close_index, current_date, 7),
                "return_30d_pct": calendar_return(close_index, current_date, 30),
                "return_90d_pct": calendar_return(close_index, current_date, 90),
                "return_365d_pct": calendar_return(close_index, current_date, 365),
                "ytd_return_pct": pct(close, first_close_by_year[current_date.year]),
                "ma_7_usd": ma_7,
                "ma_30_usd": ma_30,
                "ma_90_usd": ma_90,
                "ma_200_usd": ma_200,
                "price_vs_ma_200_pct": pct(close, ma_200),
                "volatility_30d_annualized_pct": annualized_volatility(daily_returns[: position + 1]),
                **rolling_risk,
                "high_water_mark_usd": high_water_mark,
                "drawdown_from_ath_pct": pct(close, high_water_mark),
                "days_since_ath": (current_date - high_water_date).days if high_water_date else None,
                "volume_ma_30": volume_ma_30,
                "intraday_range_pct": (row["price_high_usd"] - row["price_low_usd"]) / row["price_open_usd"] * 100.0,
                "close_location_in_range_pct": (
                    (close - row["price_low_usd"]) / (row["price_high_usd"] - row["price_low_usd"]) * 100.0
                    if row["price_high_usd"] > row["price_low_usd"]
                    else None
                ),
                "halving_epoch": epoch,
                "days_since_halving": days_since_halving,
                "days_to_next_halving_est": days_to_next_halving,
                "year": current_date.year,
                "month": current_date.month,
                "quarter": (current_date.month - 1) // 3 + 1,
                "days_since_previous_row": (current_date - previous_date).days if previous_date else None,
                "source_file": row["source_file"],
            }
        onchain = onchain_by_date.get(current_date, {})
        for field in ONCHAIN_FIELDS:
            record[field] = onchain.get(field)
        record["onchain_source"] = onchain.get("source")
        # Looker Studio expects percent metrics as fractions (0.042 = 4.2%).
        # Keep the *_pct audit fields in percentage points and expose normalized
        # aliases for charts, scorecards and percent formatting.
        for pct_field in (
            "return_1d_pct", "return_7d_pct", "return_30d_pct", "return_90d_pct",
            "return_365d_pct", "ytd_return_pct", "price_vs_ma_200_pct",
            "volatility_30d_annualized_pct", "drawdown_from_ath_pct",
            "intraday_range_pct", "close_location_in_range_pct",
            "fee_share_of_miner_revenue_pct", "supply_inflation_365d_pct",
            "active_addresses_30d_change_pct", "tx_count_30d_change_pct",
            "hashrate_30d_change_pct", "market_cap_30d_change_pct",
            "var_95_30d_pct", "var_99_30d_pct", "downside_deviation_30d_annualized_pct",
            "annualized_issuance_to_market_cap_pct", "fee_share_of_miner_revenue_blockchair_pct",
            "supply_mined_pct",
        ):
            record[pct_field.removesuffix("_pct")] = ratio(record[pct_field])
        enriched.append(record)

    return enriched


def monthly_summary(rows: list[dict]) -> list[dict]:
    groups: dict[tuple[int, int], list[dict]] = {}
    for row in rows:
        groups.setdefault((row["date"].year, row["date"].month), []).append(row)

    result = []
    for (year, month), items in sorted(groups.items()):
        first, last = items[0], items[-1]
        month_start = dt.date(year, month, 1)
        next_month = dt.date(year + (month == 12), month % 12 + 1, 1)
        month_end = next_month - dt.timedelta(days=1)
        running_max = -math.inf
        max_drawdown = 0.0
        for item in items:
            running_max = max(running_max, item["price_close_usd"])
            max_drawdown = min(max_drawdown, pct(item["price_close_usd"], running_max) or 0.0)
        record = {
                "year": year,
                "month": month,
                "month_label": f"{year}-{month:02d}",
                "first_date": first["date"],
                "last_date": last["date"],
                "first_close_usd": first["price_close_usd"],
                "last_close_usd": last["price_close_usd"],
                "monthly_return_pct": pct(last["price_close_usd"], first["price_close_usd"]),
                "month_high_close_usd": max(item["price_close_usd"] for item in items),
                "month_low_close_usd": min(item["price_close_usd"] for item in items),
                "month_max_drawdown_pct": max_drawdown,
                "avg_volume": sum(item["volume"] for item in items) / len(items),
                "observations": len(items),
                "is_partial_month": first["date"] > month_start or last["date"] < month_end,
            }
        record["monthly_return"] = ratio(record["monthly_return_pct"])
        record["month_max_drawdown"] = ratio(record["month_max_drawdown_pct"])
        result.append(record)
    return result


def yearly_summary(rows: list[dict]) -> list[dict]:
    groups: dict[int, list[dict]] = {}
    for row in rows:
        groups.setdefault(row["date"].year, []).append(row)

    result = []
    for year, items in sorted(groups.items()):
        first, last = items[0], items[-1]
        returns = [item["return_1d_pct"] for item in items if item["return_1d_pct"] is not None]
        running_max = -math.inf
        max_drawdown = 0.0
        for item in items:
            running_max = max(running_max, item["price_close_usd"])
            max_drawdown = min(max_drawdown, pct(item["price_close_usd"], running_max) or 0.0)
        # Returns are stored in percentage points, so the annualized result
        # remains in percentage points after multiplying by sqrt(365).
        realized_vol = statistics.stdev(returns) * math.sqrt(365) if len(returns) >= 2 else None
        record = {
                "year": year,
                "first_date": first["date"],
                "last_date": last["date"],
                "first_close_usd": first["price_close_usd"],
                "last_close_usd": last["price_close_usd"],
                "year_return_pct": pct(last["price_close_usd"], first["price_close_usd"]),
                "min_close_usd": min(item["price_close_usd"] for item in items),
                "max_close_usd": max(item["price_close_usd"] for item in items),
                "avg_close_usd": sum(item["price_close_usd"] for item in items) / len(items),
                "avg_volume": sum(item["volume"] for item in items) / len(items),
                "realized_vol_annualized_pct": realized_vol,
                "year_max_drawdown_pct": max_drawdown,
                "observations": len(items),
                "is_partial_year": first["date"].month != 1 or last["date"].month != 12,
            }
        record["year_return"] = ratio(record["year_return_pct"])
        record["realized_vol_annualized"] = ratio(record["realized_vol_annualized_pct"])
        record["year_max_drawdown"] = ratio(record["year_max_drawdown_pct"])
        result.append(record)
    return result


def price_on_or_after(rows: list[dict], target: dt.date) -> tuple[dt.date, float] | None:
    dates = [row["date"] for row in rows]
    if not dates or target < dates[0]:
        return None
    position = bisect.bisect_left(dates, target)
    if position >= len(rows):
        return None
    row = rows[position]
    return row["date"], row["price_close_usd"]


def halving_cycles(rows: list[dict]) -> list[dict]:
    result = []
    for item in HALVINGS:
        base = price_on_or_after(rows, item["date"])
        record = {
            "epoch": item["epoch"],
            "halving_date": item["date"],
            "block_height": item["block"],
            "reward_before_ltc": item["before"],
            "reward_after_ltc": item["after"],
            "is_estimated": item["estimated"],
            "price_on_or_after_date_usd": base[1] if base else None,
            "price_date_used": base[0] if base else None,
        }
        for horizon in (30, 90, 180, 365):
            future = price_on_or_after(rows, item["date"] + dt.timedelta(days=horizon)) if base else None
            record[f"price_plus_{horizon}d_usd"] = future[1] if future else None
            record[f"return_{horizon}d_pct"] = pct(future[1], base[1]) if future and base else None
        record["notes"] = (
            "Next halving date is an estimate based on the 840,000-block interval and average block time; "
            "not a protocol timestamp."
            if item["estimated"]
            else "Known Litecoin halving. Price observations use the first available close on/after the date."
        )
        for pct_field in ("return_30d_pct", "return_90d_pct", "return_180d_pct", "return_365d_pct"):
            record[pct_field.removesuffix("_pct")] = ratio(record[pct_field])
        result.append(record)
    return result


