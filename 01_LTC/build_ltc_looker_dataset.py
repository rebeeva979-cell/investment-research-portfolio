def load_rows() -> list[dict]:
    if not INPUT_CSV.exists():
        raise FileNotFoundError(f"Input file not found: {INPUT_CSV}")

    rows: list[dict] = []
    with INPUT_CSV.open(newline="", encoding="utf-8") as fh:
        for raw in csv.DictReader(fh):
            row = dict(raw)
            row["date"] = dt.date.fromisoformat(raw["date"])
            for field in PRICE_FIELDS:
                row[field] = float(raw[field])
            row["volume"] = float(raw["volume"])
            row["return_1d_pct"] = float(raw["return_1d_pct"]) if raw["return_1d_pct"].strip() else None
            rows.append(row)

    rows.sort(key=lambda item: item["date"])
    return rows


def load_optional_csv(path: Path) -> list[dict]:
    """Load an optional research source without inventing missing values."""
    if not path.exists():
        return []
    rows: list[dict] = []
    with path.open(newline="", encoding="utf-8") as fh:
        for raw in csv.DictReader(fh):
            row: dict = {}
            for key, value in raw.items():
                if key == "date" and value:
                    row[key] = dt.date.fromisoformat(value[:10])
                elif key in {"asset", "asset_name", "source", "data_note", "catalog_metrics_available"}:
                    row[key] = value
                elif value in (None, ""):
                    row[key] = None
                else:
                    try:
                        row[key] = float(value)
                    except (TypeError, ValueError):
                        row[key] = value
            rows.append(row)
    return rows


