def main() -> None:
    rows = load_rows()
    onchain_rows = load_onchain_rows()
    peer_rows = load_peer_rows()
    catalog_rows = load_optional_csv(BASE_DIR / "LTC_CATALOG.csv")
    validation = validate(rows)
    # Keep peer comparisons on the same as-of date as the uploaded market row.
    # Coin Metrics may publish one or more newer network observations.
    peer_rows = [row for row in peer_rows if not row.get("date") or row["date"] <= validation["end"]]
    enriched = enrich(rows, onchain_rows)
    monthly = monthly_summary(enriched)
    yearly = yearly_summary(enriched)
    cycles = halving_cycles(enriched)
    kpi = latest_kpi(enriched, validation)

    write_csv(OUTPUT_CSV, enriched)
    write_csv(OUTPUT_KPI_CSV, [kpi])
    build_workbook(enriched, validation, kpi, onchain_rows, monthly, yearly, cycles, peer_rows, catalog_rows)

    print(f"OK: {OUTPUT_CSV}")
    print(f"OK: {OUTPUT_KPI_CSV}")
    print(f"OK: {OUTPUT_XLSX}")
    print(f"rows={len(enriched)} period={validation['start']}..{validation['end']} gaps={len(validation['gaps'])} onchain={bool(onchain_rows)} peers={len(peer_rows)}")


if __name__ == "__main__":
    main()
