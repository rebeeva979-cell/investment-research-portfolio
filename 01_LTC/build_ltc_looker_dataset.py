def autosize(ws, max_width: int = 42) -> None:
    for column in ws.columns:
        length = 0
        letter = get_column_letter(column[0].column)
        for cell in column:
            value = "" if cell.value is None else str(cell.value)
            length = max(length, len(value))
        ws.column_dimensions[letter].width = min(max(12, length + 2), max_width)


def format_data_sheet(
    ws,
    date_columns: set[str],
    price_columns: set[str],
    percent_columns: set[str],
    volume_columns: set[str],
    fraction_columns: set[str] | None = None,
) -> None:
    fraction_columns = fraction_columns or set()
    headers = {cell.value: cell.column for cell in ws[1]}
    for name, column in headers.items():
        letter = get_column_letter(column)
        for cell in ws.iter_rows(min_row=2, min_col=column, max_col=column):
            target = cell[0]
            if name in date_columns:
                target.number_format = DATE_FORMAT
            elif name in price_columns:
                target.number_format = PRICE_FORMAT
            elif name in fraction_columns:
                target.number_format = "0.00%"
            elif name in percent_columns:
                target.number_format = PERCENT_FORMAT
            elif name in volume_columns:
                target.number_format = VOLUME_FORMAT
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions


