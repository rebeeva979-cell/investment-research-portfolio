def decision_snapshot(rows: list[dict]) -> list[dict]:
    """Create explicit, auditable decision gates, not a buy/sell forecast."""
    latest = rows[-1]
    as_of = latest["date"]
    price_vs_ma = latest.get("price_vs_ma_200_pct")
    ret30 = latest.get("return_30d_pct")
    ret90 = latest.get("return_90d_pct")
    active30 = latest.get("active_addresses_30d_change_pct")
    tx30 = latest.get("tx_count_30d_change_pct")
    hash30 = latest.get("hashrate_30d_change_pct")
    data_ok = bool(latest.get("onchain_source"))

    if price_vs_ma is None:
        trend_status = "NO DATA"
    else:
        trend_status = "PASS" if price_vs_ma >= 0 else "FAIL"
    if ret30 is None or ret90 is None:
        momentum_status = "NO DATA"
    elif ret30 > 0 and ret90 > 0:
        momentum_status = "PASS"
    elif ret30 < 0 and ret90 < 0:
        momentum_status = "FAIL"
    else:
        momentum_status = "MIXED"
    if active30 is None or tx30 is None:
        adoption_status = "NO DATA"
    elif active30 > 0 and tx30 > 0:
        adoption_status = "PASS"
    elif active30 < 0 and tx30 < 0:
        adoption_status = "FAIL"
    else:
        adoption_status = "MIXED"
    if hash30 is None or latest.get("block_count") is None:
        security_status = "NO DATA"
    else:
        security_status = "PASS" if hash30 >= 0 and latest["block_count"] > 0 else "FAIL"

    rows_out = [
        {
            "as_of_date": as_of,
            "gate": "Market trend",
            "metric": "price_vs_ma_200",
            "current_value": ratio(price_vs_ma),
            "rule": "PASS when close is at or above MA200",
            "status": trend_status,
            "interpretation": "Trend confirmation gate; not an entry trigger",
        },
        {
            "as_of_date": as_of,
            "gate": "Momentum",
            "metric": "return_30d and return_90d",
            "current_value": f"{ret30}; {ret90}",
            "rule": "PASS only when both horizons are positive",
            "status": momentum_status,
            "interpretation": "Avoid treating a single-day rebound as a regime change",
        },
        {
            "as_of_date": as_of,
            "gate": "Adoption",
            "metric": "active_addresses_30d_change and tx_count_30d_change",
            "current_value": f"{active30}; {tx30}",
            "rule": "PASS only when both network activity changes are positive",
            "status": adoption_status,
            "interpretation": "Addresses are a proxy, not unique users",
        },
        {
            "as_of_date": as_of,
            "gate": "Security",
            "metric": "hashrate_30d_change and block_count",
            "current_value": f"{hash30}; {latest.get('block_count')}",
            "rule": "PASS when hashrate is not falling and blocks are present",
            "status": security_status,
            "interpretation": "Hashrate is a network-security proxy, not a complete attack-risk model",
        },
        {
            "as_of_date": as_of,
            "gate": "Data completeness",
            "metric": "onchain_source",
            "current_value": latest.get("onchain_source") or "missing",
            "rule": "PASS only when the on-chain source was refreshed",
            "status": "PASS" if data_ok else "FAIL",
            "interpretation": "No new risk should be added when key data is stale or missing",
        },
    ]
    hard_fails = sum(row["status"] == "FAIL" for row in rows_out[:4])
    passes = sum(row["status"] == "PASS" for row in rows_out[:4])
    overall = "CONFIRMATION" if passes >= 3 and hard_fails == 0 else "CAUTION" if hard_fails <= 1 else "DEFENSIVE"
    rows_out.append(
        {
            "as_of_date": as_of,
            "gate": "Overall research state",
            "metric": "four-gate summary",
            "current_value": f"passes={passes}; fails={hard_fails}",
            "rule": "Confirmation requires >=3 PASS and no hard FAIL",
            "status": overall,
            "interpretation": "Research state only; combine with position sizing and personal risk limits",
        }
    )
    return rows_out


